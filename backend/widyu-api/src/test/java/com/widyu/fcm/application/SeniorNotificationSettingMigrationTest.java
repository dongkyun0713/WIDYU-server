package com.widyu.fcm.application;

import static org.assertj.core.api.Assertions.assertThat;

import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

class SeniorNotificationSettingMigrationTest {

    @Test
    @DisplayName("시니어 일반 알림을 옮기면 꺼진 회원의 네 항목만 꺼지고 보호자 설정은 유지된다")
    void 시니어_일반_알림을_옮기면_네_항목과_보호자_설정이_분리된다() throws Exception {
        // given
        Path script = Path.of("scripts/mysql/migrate_senior_notification_settings.sql");
        if (!Files.exists(script)) {
            script = Path.of("../../scripts/mysql/migrate_senior_notification_settings.sql");
        }
        String content = Files.readString(script);
        String dml = content.substring(content.indexOf("-- H2-DML-BEGIN"), content.indexOf("-- H2-DML-END"));
        dml = dml.replaceAll("(?m)^--.*$", "");
        try (Connection connection = DriverManager.getConnection(
                "jdbc:h2:mem:senior_setting_migration;MODE=MySQL;DB_CLOSE_DELAY=-1");
             Statement statement = connection.createStatement()) {
            statement.execute("CREATE TABLE member (id BIGINT PRIMARY KEY, type VARCHAR(16) NOT NULL)");
            statement.execute("CREATE TABLE member_notification_setting "
                    + "(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, member_id BIGINT NOT NULL, "
                    + "category VARCHAR(32) NOT NULL, enabled TINYINT NOT NULL, UNIQUE(member_id, category))");
            statement.execute("INSERT INTO member (id, type) VALUES "
                    + "(1, 'SENIOR'), (2, 'SENIOR'), (3, 'GUARDIAN'), (4, 'SENIOR'), (5, 'GUARDIAN')");
            statement.execute("INSERT INTO member_notification_setting (member_id, category, enabled) VALUES "
                    + "(1, 'GENERAL', 0), (2, 'GENERAL', 1), "
                    + "(3, 'GENERAL', 0), (5, 'GENERAL', 1)");

            // when
            for (int run = 0; run < 2; run++) {
                for (String command : dml.split(";")) {
                    String sql = command.trim();
                    if (sql.equalsIgnoreCase("START TRANSACTION") || sql.isBlank()) {
                        continue;
                    }
                    if (sql.startsWith("DROP TEMPORARY TABLE")) {
                        sql = sql.replace("DROP TEMPORARY TABLE", "DROP TABLE");
                    }
                    statement.execute(sql);
                }
            }

            // then
            try (ResultSet rows = statement.executeQuery(
                    "SELECT member_id, category, enabled FROM member_notification_setting "
                            + "ORDER BY member_id, category")) {
                for (String category : new String[]{"ALBUM", "ETC", "GOAL", "HOME"}) {
                    assertThat(rows.next()).isTrue();
                    assertThat(rows.getLong("member_id")).isEqualTo(1L);
                    assertThat(rows.getString("category")).isEqualTo(category);
                    assertThat(rows.getInt("enabled")).isZero();
                }
                assertThat(rows.next()).isTrue();
                assertThat(rows.getLong("member_id")).isEqualTo(3L);
                assertThat(rows.getString("category")).isEqualTo("GENERAL");
                assertThat(rows.getInt("enabled")).isZero();
                assertThat(rows.next()).isTrue();
                assertThat(rows.getLong("member_id")).isEqualTo(5L);
                assertThat(rows.getString("category")).isEqualTo("GENERAL");
                assertThat(rows.getInt("enabled")).isEqualTo(1);
                assertThat(rows.next()).isFalse();
            }
        }
    }
}
